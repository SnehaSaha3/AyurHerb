# LETTERHEAD
# ============================================================

def _letterhead(
    invoice_number: str,
    order_id: str,
) -> list:

    logo_drawing = draw_logo(
        0,
        0,
        size=30,
    )

    header_table = Table(
        [
            [
                logo_drawing,
                Paragraph(
                    f'<font size="7" color="{HEX_MUTED}">'
                    f'INVOICE #{invoice_number}<br/>'
                    f'Order ref: {order_id}'
                    f'</font>',
                    style_body,
                ),
            ]
        ],
        colWidths=[
            90 * mm,
            80 * mm,
        ],
    )

    header_table.setStyle(
        TableStyle(
            [
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "MIDDLE",
                ),
                (
                    "ALIGN",
                    (1, 0),
                    (1, 0),
                    "RIGHT",
                ),
            ]
        )
    )

    tagline = Paragraph(
        f'<font size="8" color="{HEX_ACCENT}">'
        f'<i>{BRAND_TAGLINE}</i>'
        f'</font>',
        style_body,
    )

    return [
        header_table,
        Spacer(1, 2 * mm),
        tagline,
        Spacer(1, 3 * mm),
        HRFlowable(
            width="100%",
            thickness=1.2,
            color=COLOR_PRIMARY,
        ),
        Spacer(1, 5 * mm),
    ]


