# ============================================================
# DATE / TIME FORMATTER
# ============================================================

def _format_transaction_datetime(
    transaction_at: datetime | None,
) -> tuple[str, str]:
    """
    Convert the canonical transaction timestamp into
    human-readable Indian date and time.

    Example:

        09 September 2026
        08:58 PM IST

    The backend sends the timestamp as the actual payment /
    escrow funding timestamp.
    """

    if not transaction_at:
        return "N/A", "N/A"

    try:
        # If the datetime has no timezone, treat it as UTC
        # because Node sends the timestamp in ISO/UTC form.
        if transaction_at.tzinfo is None:
            transaction_at = transaction_at.replace(
                tzinfo=ZoneInfo("UTC")
            )

        india_time = transaction_at.astimezone(
            ZoneInfo("Asia/Kolkata")
        )

        date_text = india_time.strftime(
            "%d %B %Y"
        )

        time_text = india_time.strftime(
            "%I:%M %p IST"
        )

        return date_text, time_text

    except Exception:
        return "N/A", "N/A"


# ============================================================
# QR CODE
# ============================================================

def _make_qr_flowable(
    verify_url: str,
    size_mm: float = 28,
) -> Image:

    qr = qrcode.QRCode(
        border=1,
        box_size=8,
    )

    qr.add_data(verify_url)
    qr.make(fit=True)

    img = qr.make_image(
        fill_color="#12241A",
        back_color="white",
    )

    buf = io.BytesIO()

    img.save(
        buf,
        format="PNG",
    )

    buf.seek(0)

    return Image(
        buf,
        width=size_mm * mm,
        height=size_mm * mm,
    )


