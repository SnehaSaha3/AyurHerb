# ============================================================
# BUILD PDF
# ============================================================

def build_invoice_pdf(
    req: InvoiceRequest,
    invoice_notes: str,
    verify_url: str,
) -> bytes:

    buf = io.BytesIO()

    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
    )

    story = []

    # --------------------------------------------------------
    # LETTERHEAD
    # --------------------------------------------------------

    story += _letterhead(
        req.invoiceNumber,
        req.orderId,
    )

    # --------------------------------------------------------
    # TRANSACTION DATE / TIME
    # --------------------------------------------------------

    story.append(
        Paragraph(
            "TRANSACTION INFORMATION",
            style_label,
        )
    )

    story.append(
        Spacer(1, 2 * mm)
    )

    story.append(
        _transaction_block(req)
    )

    story.append(
        Spacer(1, 7 * mm)
    )

    # --------------------------------------------------------
    # BUYER / SELLER
    # --------------------------------------------------------

    story.append(
        _party_block(req)
    )

    story.append(
        Spacer(1, 8 * mm)
    )

    # --------------------------------------------------------
    # ORDER DETAILS
    # --------------------------------------------------------

    story.append(
        Paragraph(
            "ORDER DETAILS",
            style_label,
        )
    )

    story.append(
        Spacer(1, 2 * mm)
    )

    story.append(
        _line_items_table(req)
    )

    story.append(
        Spacer(1, 8 * mm)
    )

    # --------------------------------------------------------
    # PAYMENT
    # --------------------------------------------------------

    story.append(
        Paragraph(
            "PAYMENT DUE FROM COMPANY",
            style_label,
        )
    )

    story.append(
        Spacer(1, 2 * mm)
    )

    story.append(
        _charges_table(req)
    )

    story.append(
        Spacer(1, 8 * mm)
    )

    # --------------------------------------------------------
    # ESCROW TERMS
    # --------------------------------------------------------

    story.append(
        Paragraph(
            "ESCROW RELEASE TERMS",
            style_label,
        )
    )

    story.append(
        Spacer(1, 2 * mm)
    )

    story.append(
        _payment_terms_table(req)
    )

    story.append(
        Spacer(1, 8 * mm)
    )

    # --------------------------------------------------------
    # NOTES
    # --------------------------------------------------------

    if invoice_notes:

        story.append(
            Paragraph(
                "NOTES",
                style_label,
            )
        )

        story.append(
            Spacer(1, 1.5 * mm)
        )

        story.append(
            Paragraph(
                invoice_notes,
                style_notes,
            )
        )

        story.append(
            Spacer(1, 8 * mm)
        )

    # --------------------------------------------------------
    # QR VERIFICATION
    # --------------------------------------------------------

    qr_table = Table(
        [
            [
                _make_qr_flowable(
                    verify_url
                ),
                Paragraph(
                    f'<font size="8" color="{HEX_MUTED}">'
                    f"<b>Scan to verify</b><br/>"
                    f"This QR code opens the public "
                    f"AyurHerb verification record for "
                    f"this order's crop provenance, "
                    f"invoice details and blockchain proof."
                    f"<br/><br/>"
                    f"Farmers: print this code on shipment packs."
                    f"</font>",
                    style_body,
                ),
            ]
        ],
        colWidths=[
            30 * mm,
            130 * mm,
        ],
    )

    qr_table.setStyle(
        TableStyle(
            [
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "MIDDLE",
                ),
            ]
        )
    )

    story.append(
        qr_table
    )

    # --------------------------------------------------------
    # FOOTER
    # --------------------------------------------------------

    story.append(
        Spacer(1, 10 * mm)
    )

    story.append(
        HRFlowable(
            width="100%",
            thickness=0.5,
            color=COLOR_ACCENT,
        )
    )

    story.append(
        Spacer(1, 2 * mm)
    )

    story.append(
        Paragraph(
            f'<font size="7" color="{HEX_MUTED}">'
            f"Generated by {BRAND_NAME} — funds held in "
            f"platform escrow (Razorpay, test mode) until "
            f"milestone release, verified on-chain."
            f"</font>",
            style_body,
        )
    )

    # --------------------------------------------------------
    # BUILD
    # --------------------------------------------------------

    doc.build(story)

    buf.seek(0)

    return buf.read()